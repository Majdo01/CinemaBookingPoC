
-- Table for seat reservations.
-- Each reservation belongs to one screening.
-- A seat can only be reserved once per screening.

CREATE TABLE reservations (
                              id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              screening_id BIGINT NOT NULL,
                              seat_number  VARCHAR(255) NOT NULL,

                              CONSTRAINT fk_reservations_screening
                                  FOREIGN KEY (screening_id)
                                      REFERENCES screenings(id),

                              CONSTRAINT uq_reservations_screening_seat
                                  UNIQUE (screening_id, seat_number)
);
